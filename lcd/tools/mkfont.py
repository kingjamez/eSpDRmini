#!/usr/bin/env python3
"""Generates main/fonts.c and main/fonts.h: anti-aliased (4-bit) bitmap fonts
rendered from the DejaVu fonts that ship with matplotlib.

    ../.venv/bin/python tools/mkfont.py      (from lcd/)
"""
import os

import matplotlib
from matplotlib import ft2font
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "main")
TTF = os.path.join(os.path.dirname(matplotlib.__file__), "mpl-data", "fonts", "ttf")

# name, file, pixel size
FONTS = [
    ("font_small", "DejaVuSans.ttf", 12),
    ("font_label", "DejaVuSans.ttf", 14),
    ("font_body", "DejaVuSans.ttf", 16),
    ("font_bold", "DejaVuSans-Bold.ttf", 16),
    ("font_title", "DejaVuSans-Bold.ttf", 22),
    ("font_big", "DejaVuSans-Bold.ttf", 28),
    ("font_mono", "DejaVuSansMono.ttf", 14),
    ("font_mono_big", "DejaVuSansMono-Bold.ttf", 24),
]
EXTRA = "°µΔ·–—−×±≥≤…▲▼◀▶⏸■●←→↑↓⌫✓"
CHARS = [chr(c) for c in range(32, 127)] + list(EXTRA)


def render(path, size):
    font = ImageFont.truetype(path, size)
    face = ft2font.FT2Font(path)
    ascent, descent = font.getmetrics()
    glyphs, bits = [], bytearray()
    for ch in CHARS:
        if ch != " " and face.get_char_index(ord(ch)) == 0:
            continue
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        nibbles = []
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
            nibbles = [(v * 15 + 127) // 255 for v in img.tobytes()]
        if len(nibbles) % 2:
            nibbles.append(0)
        off = len(bits)
        bits += bytes(nibbles[i] << 4 | nibbles[i + 1] for i in range(0, len(nibbles), 2))
        glyphs.append((ord(ch), w, h, x0, ascent + y0, round(font.getlength(ch)), off))
    return ascent, ascent + descent, sorted(glyphs), bits


def main():
    c = ['/* Generated by tools/mkfont.py from the DejaVu fonts (Bitstream Vera',
         ' * license, see README.md). Do not edit. */',
         '#include "fonts.h"', '']
    h = ['/* Generated by tools/mkfont.py. Do not edit. */', '#pragma once',
         '#include "gfx.h"', '']
    for name, file, size in FONTS:
        ascent, height, glyphs, bits = render(os.path.join(TTF, file), size)
        c.append(f"static const uint8_t {name}_bits[] = {{")
        for i in range(0, len(bits), 24):
            c.append("    " + ",".join(str(b) for b in bits[i:i + 24]) + ",")
        c.append("};")
        c.append(f"static const glyph_t {name}_glyphs[] = {{")
        for g in glyphs:
            c.append("    {%d,%d,%d,%d,%d,%d,%d}," % g)
        c.append("};")
        c.append(f"const font_t {name} = {{{name}_glyphs, {len(glyphs)}, {ascent}, {height}, {name}_bits}};")
        c.append("")
        h.append(f"extern const font_t {name}; /* {file} {size} px */")
    with open(os.path.join(OUT, "fonts.c"), "w") as f:
        f.write("\n".join(c) + "\n")
    with open(os.path.join(OUT, "fonts.h"), "w") as f:
        f.write("\n".join(h) + "\n")


if __name__ == "__main__":
    main()
